/// Each error has the code `owx-syntax`, is at the span named, and breaks
/// its rule: the document gives the header's triple only.
#[track_caller]
fn rule_errors(body: &str, expected: &[(&str, &str)]) {
    let (text, p) = faults(body);
    let got: Vec<(&str, &str)> = errors(&text, &p)
        .into_iter()
        .map(|(code, at, message)| {
            assert_eq!(code, CODE, "{message}");
            (at, message)
        })
        .collect();
    assert_eq!(got, expected, "{text}");
    assert_eq!(p.triples.len(), 1, "{text}");
}

