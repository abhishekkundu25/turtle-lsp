/// Each of the seven atom kinds, alone in a body, with a variable in each
/// argument it has.
#[test]
fn each_atom_kind_with_variables() {
    let (x, y, v) = (var("x"), var("y"), var("v"));
    let (fx, fy, fv) = (fvar("x"), fvar("y"), fvar("v"));
    let cases: [(String, String); 7] = [
        (
            el("ClassAtom", &["<Class abbreviatedIRI=\":A\"/>", &x]),
            format!("ClassAtom(:A {fx})"),
        ),
        (
            el(
                "DataRangeAtom",
                &["<Datatype abbreviatedIRI=\"xsd:integer\"/>", &v],
            ),
            format!("DataRangeAtom(xsd:integer {fv})"),
        ),
        (
            el(
                "ObjectPropertyAtom",
                &["<ObjectProperty abbreviatedIRI=\":p\"/>", &x, &y],
            ),
            format!("ObjectPropertyAtom(:p {fx} {fy})"),
        ),
        (
            el(
                "DataPropertyAtom",
                &["<DataProperty abbreviatedIRI=\":d\"/>", &x, &v],
            ),
            format!("DataPropertyAtom(:d {fx} {fv})"),
        ),
        (
            format!("<BuiltInAtom abbreviatedIRI=\"swrlb:add\">{v}{x}</BuiltInAtom>"),
            format!("BuiltInAtom(swrlb:add {fv} {fx})"),
        ),
        (
            el("SameIndividualAtom", &[&x, &y]),
            format!("SameIndividualAtom({fx} {fy})"),
        ),
        (
            el("DifferentIndividualsAtom", &[&x, &y]),
            format!("DifferentIndividualsAtom({fx} {fy})"),
        ),
    ];
    for (atom, theirs) in &cases {
        same_rule(&rule(&[atom], &[]), &frule(&[theirs], &[]));
        same_rule(&rule(&[], &[atom]), &frule(&[], &[theirs]));
    }
    // All seven in one body, a head of two.
    let atoms: Vec<&str> = cases.iter().map(|c| c.0.as_str()).collect();
    let theirs: Vec<&str> = cases.iter().map(|c| c.1.as_str()).collect();
    same_rule(&rule(&atoms, &atoms[..2]), &frule(&theirs, &theirs[..2]));
}

