/// A rule's annotations, one annotated itself, come before its body; the
/// predicate of each rule triple is at the element's name.
#[test]
fn an_annotated_rule() {
    let atom = el("ClassAtom", &["<Class abbreviatedIRI=\":A\"/>", &var("x")]);
    let annotation = "<Annotation><Annotation><AnnotationProperty abbreviatedIRI=\"rdfs:label\"/><Literal>inner</Literal></Annotation><AnnotationProperty abbreviatedIRI=\"rdfs:comment\"/><Literal>why</Literal></Annotation>";
    let (text, p) = same_rule(
        &el(
            "DLSafeRule",
            &[annotation, &el("Body", &[&atom]), &el("Head", &[&atom])],
        ),
        &format!(
            "DLSafeRule(Annotation(Annotation(rdfs:label \"inner\") rdfs:comment \"why\") Body(ClassAtom(:A {x})) Head(ClassAtom(:A {x})))",
            x = fvar("x")
        ),
    );
    // Each rule triple's predicate at the element its rule maps.
    let at = |s: crate::syntax::Span| &text[s.start as usize..s.end as usize];
    let swrl = |name: &str| {
        let t = p
            .triples
            .iter()
            .find(|t| t.p.as_str() == format!("http://www.w3.org/2003/11/swrl#{name}"))
            .unwrap();
        at(t.p_span)
    };
    assert_eq!(
        (swrl("body"), swrl("head"), swrl("classPredicate")),
        ("Body", "Head", "ClassAtom")
    );
}

