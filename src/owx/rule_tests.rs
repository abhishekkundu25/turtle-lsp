/// What neither ROBOT file shows is not read: a variable or a built-in's
/// IRI as a child element (the Functional shape), an anonymous individual
/// as an argument (OWL API does not read one in Functional syntax), a
/// variable outside an atom, a rule part outside a rule, `Head` before
/// `Body`, a rule inside an axiom.
#[test]
fn a_rule_element_in_a_place_the_evidence_does_not_show() {
    let x = var("x");
    let class = "<Class abbreviatedIRI=\":A\"/>";
    rule_errors(
        &rule(
            &[&el(
                "ClassAtom",
                &[
                    class,
                    "<Variable><IRI>http://example.org/var#x</IRI></Variable>",
                ],
            )],
            &[],
        ),
        &[(
            "Variable",
            "<Variable> needs the attribute IRI or abbreviatedIRI",
        )],
    );
    rule_errors(
        &rule(
            &[&el(
                "ClassAtom",
                &[
                    class,
                    "<Variable IRI=\"http://example.org/var#x\"><IRI>http://example.org/var#x</IRI></Variable>",
                ],
            )],
            &[],
        ),
        &[("IRI", "<Variable> holds no element, found <IRI>")],
    );
    rule_errors(
        &rule(
            &[&format!(
                "<BuiltInAtom><IRI>http://www.w3.org/2003/11/swrlb#add</IRI>{x}</BuiltInAtom>"
            )],
            &[],
        ),
        &[(
            "BuiltInAtom",
            "<BuiltInAtom> needs the attribute IRI or abbreviatedIRI",
        )],
    );
    rule_errors(
        &rule(
            &[&el(
                "ClassAtom",
                &[class, "<AnonymousIndividual nodeID=\"b\"/>"],
            )],
            &[],
        ),
        &[(
            "AnonymousIndividual",
            "Expected an individual or a variable, found <AnonymousIndividual>",
        )],
    );
    rule_errors(
        &el("ClassAssertion", &[class, &x]),
        &[("Variable", "Expected an individual, found <Variable>")],
    );
    rule_errors(
        &el("SubClassOf", &[&x, class]),
        &[("Variable", "Expected a class expression, found <Variable>")],
    );
    rule_errors(
        &el("Body", &[]),
        &[(
            "Body",
            "Expected <Prefix>, <Import>, <Annotation> or an axiom, found <Body>",
        )],
    );
    rule_errors(
        &el("DLSafeRule", &[&el("Head", &[]), &el("Body", &[])]),
        &[("Head", "Expected <Body>, found <Head>")],
    );
    rule_errors(
        &el(
            "DLSafeRule",
            &[&el("Body", &[]), &el("Head", &[]), &el("Head", &[])],
        ),
        &[("Head", "Expected the end of <DLSafeRule>, found <Head>")],
    );
    rule_errors(
        &el("SubClassOf", &[&rule(&[], &[]), class]),
        &[(
            "DLSafeRule",
            "Expected a class expression, found <DLSafeRule>",
        )],
    );
    rule_errors(
        "<DLSafeRule><Body/></DLSafeRule>",
        &[("</DLSafeRule>", "Expected <Head>, found </DLSafeRule>")],
    );
}
