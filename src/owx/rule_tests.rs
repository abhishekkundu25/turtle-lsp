// ---- graphs ----

fn term(n: &Node) -> Term {
    use oxrdf::{BlankNode, Literal, NamedNode};
    match n {
        Node::Iri(i) => NamedNode::new_unchecked(i.as_str()).into(),
        Node::Blank(b) => BlankNode::new_unchecked(format!("b{}", b.0)).into(),
        Node::Literal {
            value,
            datatype,
            lang,
            ..
        } => match lang {
            Some(l) => Literal::new_language_tagged_literal_unchecked(&**value, l.as_str()).into(),
            None => {
                Literal::new_typed_literal(&**value, NamedNode::new_unchecked(datatype.as_str()))
                    .into()
            }
        },
        Node::Triple(_) => unreachable!("no triple terms"),
    }
}

/// The graph of a parse, its blank nodes named canonically: two parses
/// whose items come in another order compare equal.
fn graph(p: &Parsed) -> Graph {
    let mut g = Graph::new();
    for t in &p.triples {
        let s = match term(&t.s) {
            Term::NamedNode(n) => NamedOrBlankNode::from(n),
            Term::BlankNode(b) => b.into(),
            t => panic!("not a subject: {t}"),
        };
        g.insert(&oxrdf::Triple::new(
            s,
            oxrdf::NamedNode::new_unchecked(t.p.as_str()),
            term(&t.o),
        ));
    }
    g.canonicalize(CanonicalizationAlgorithm::Unstable);
    g
}

/// The triples only one of `ours` and `theirs` has, if any.
fn difference(ours: &Parsed, theirs: &Parsed) -> Option<String> {
    let (a, b) = (graph(ours), graph(theirs));
    if a == b {
        return None;
    }
    let mut out = format!("OWL/XML {} triples, Functional {}\n", a.len(), b.len());
    for (who, x, y) in [("OWL/XML", &a, &b), ("Functional", &b, &a)] {
        for t in x.iter().filter(|t| !y.contains(*t)).take(20) {
            out.push_str(&format!("  only {who}: {t}\n"));
        }
    }
    Some(out)
}

// ---- documents ----

/// The prefixes the rules below use, beside `:` and `ex:`.
const PREFIXES: &str = "<Prefix name=\"xsd\" IRI=\"http://www.w3.org/2001/XMLSchema#\"/>\n<Prefix name=\"rdfs\" IRI=\"http://www.w3.org/2000/01/rdf-schema#\"/>\n<Prefix name=\"swrlb\" IRI=\"http://www.w3.org/2003/11/swrlb#\"/>\n";

fn doc(body: &str) -> String {
    owx(&format!("{PREFIXES}{body}"))
}

fn fs(body: &str) -> String {
    format!(
        "Prefix(swrlb:=<http://www.w3.org/2003/11/swrlb#>)\n{}",
        ofn(body)
    )
}

fn el(name: &str, inner: &[&str]) -> String {
    format!("<{name}>{}</{name}>", inner.concat())
}

/// `<Variable IRI="http://example.org/var#n"/>`, as the fixture writes it.
fn var(n: &str) -> String {
    format!("<Variable IRI=\"http://example.org/var#{n}\"/>")
}

/// The same in Functional syntax.
fn fvar(n: &str) -> String {
    format!("Variable(<http://example.org/var#{n}>)")
}

/// A rule of `body` and `head`, each atoms.
fn rule(body: &[&str], head: &[&str]) -> String {
    el("DLSafeRule", &[&el("Body", body), &el("Head", head)])
}

/// The same in Functional syntax.
fn frule(body: &[&str], head: &[&str]) -> String {
    format!(
        "DLSafeRule(Body({}) Head({}))",
        body.join(" "),
        head.join(" ")
    )
}

/// The OWL/XML document of `body` reads with no error to the tree shape
/// of the Functional document of `theirs` (the signature check passes) and
/// to its graph.
#[track_caller]
fn same_rule(body: &str, theirs: &str) -> (String, Parsed) {
    let text = doc(body);
    let p = clean(&text);
    let functional_text = fs(theirs);
    let (tree, _) = reader::read(&text, Some(URL));
    assert_eq!(
        shape(&tree),
        shape(&crate::ofn::tree(&functional_text)),
        "{text}"
    );
    same_mapping(&p, &functional(&functional_text));
    (text, p)
}

/// The errors of the OWL/XML document of `body`.
fn faults(body: &str) -> (String, Parsed) {
    let text = doc(body);
    let p = read(&text, Some(URL));
    (text, p)
}

