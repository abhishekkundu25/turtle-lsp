/// A `nodeID` is its whole value: `x` and `_:x` are two anonymous
/// individuals, as `_:x` and `_:_:x` would be if Functional syntax had the
/// second.
#[test]
fn a_node_id_with_and_without_its_underscore_colon_are_two_nodes() {
    let body = "<ClassAssertion><Class abbreviatedIRI=\":A\"/><AnonymousIndividual nodeID=\"x\"/></ClassAssertion>\n<ClassAssertion><Class abbreviatedIRI=\":A\"/><AnonymousIndividual nodeID=\"_:x\"/></ClassAssertion>";
    let p = clean(&doc(body));
    let blanks: std::collections::HashSet<_> = p
        .triples
        .iter()
        .filter_map(|t| match t.s {
            Node::Blank(b) => Some(b),
            _ => None,
        })
        .collect();
    assert_eq!(blanks.len(), 2);
}

