/// The rule of [`FORMS`], an atom of each of the seven kinds and an
/// annotation, cut from the file with its prefixes and header, reads to
/// the tree shape and the graph of the rule of its Functional source.
#[test]
fn the_rule_robot_writes_reads_as_its_functional_source() {
    let start = FORMS.find("    <DLSafeRule>").unwrap();
    let end = FORMS.find("</DLSafeRule>\n").unwrap() + "</DLSafeRule>\n".len();
    let header = &FORMS[..FORMS.find("    <Import>").unwrap()];
    let text = format!("{header}{}</Ontology>\n", &FORMS[start..end]);
    let p = clean(&text);

    let rule = &FORMS_OFN[FORMS_OFN.find("DLSafeRule(").unwrap()..];
    let rule = rule.trim_end().strip_suffix(')').unwrap().trim_end();
    let theirs = format!(
        "{}{rule}\n)\n",
        &FORMS_OFN[..FORMS_OFN.find("Import(").unwrap()]
    );
    let (tree, _) = reader::read(&text, Some(URL));
    assert_eq!(shape(&tree), shape(&crate::ofn::tree(&theirs)));
    same_mapping(&p, &functional(&theirs));
    // The rule's triples: the header, the `swrl:Imp` and its annotation,
    // the lists and the atoms, the three variables.
    assert!(p.triples.len() > 40, "{}", p.triples.len());
}

/// The whole of [`FORMS`] reads with no error, to the graph of its
/// Functional source but for what OWL API changes on the way: it declares
/// `ex:Undeclared`, which the source uses without declaring, and it sorts
/// the operands of `DisjointClasses`.
#[test]
fn robot_s_owl_xml_of_the_forms_is_the_graph_of_their_source() {
    let p = clean(FORMS);
    let source = FORMS_OFN
        .replace(
            "DisjointClasses(ex:C ex:B ex:A)",
            "DisjointClasses(ex:A ex:B ex:C)",
        )
        .replace(
            "Declaration(Class(:Local))",
            "Declaration(Class(:Local))\nDeclaration(Class(ex:Undeclared))",
        );
    assert_ne!(source, FORMS_OFN);
    let theirs = functional(&source);
    assert_eq!(difference(&p, &theirs), None);
}

/// [`ROBOT_RULES`] (a variable's `abbreviatedIRI`, a built-in's `IRI`, three
