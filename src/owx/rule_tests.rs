/// Each literal of [`FORMS`] reads to the literal of its Functional source,
/// one row of the spec's table each: ROBOT writes a string with no
/// `datatypeIRI` and no `xml:lang` (row 1), a language string with
/// `xml:lang` and no `datatypeIRI` (row 2), another datatype with
/// `datatypeIRI` (row 5); it writes `"…@fr"^^rdf:PlainLiteral` as row 2 and
/// `"…@"^^rdf:PlainLiteral` and `xsd:string` as row 1, never
/// `datatypeIRI="…#PlainLiteral"`, so rows 3 and 4 have no evidence here.
#[test]
fn each_literal_robot_writes_is_the_literal_of_its_source() {
    let rows = [
        (
            "<Literal>plain</Literal>",
            "AnnotationAssertion(ex:note ex:i \"plain\")",
        ),
        (
            "<Literal xml:lang=\"en\">tagged</Literal>",
            "AnnotationAssertion(ex:note ex:i \"tagged\"@en)",
        ),
        (
            "<Literal>typed</Literal>",
            "AnnotationAssertion(ex:note ex:i \"typed\"^^xsd:string)",
        ),
        (
            "<Literal datatypeIRI=\"http://www.w3.org/2001/XMLSchema#integer\">42</Literal>",
            "AnnotationAssertion(ex:note ex:i \"42\"^^xsd:integer)",
        ),
        (
            "<Literal xml:lang=\"fr\">written out</Literal>",
            "AnnotationAssertion(ex:note ex:i \"written out@fr\"^^rdf:PlainLiteral)",
        ),
        (
            "<Literal>written out, no language</Literal>",
            "AnnotationAssertion(ex:note ex:i \"written out, no language@\"^^rdf:PlainLiteral)",
        ),
        (
            "<Literal xml:lang=\"de\">tagged data</Literal>",
            "DataPropertyAssertion(ex:d ex:j \"tagged data\"@de)",
        ),
    ];
    let header = &FORMS[..FORMS.find("    <Import>").unwrap()];
    let ofn_header = &FORMS_OFN[..FORMS_OFN.find("Import(").unwrap()];
    for (literal, source) in rows {
        assert!(FORMS_OFN.contains(source), "{source}");
        // The item of FORMS that holds the literal.
        let at = FORMS.find(literal).unwrap_or_else(|| panic!("{literal}"));
        let start = FORMS[..at].rfind("\n    <").unwrap() + 1;
        let close = if source.starts_with("Data") {
            "</DataPropertyAssertion>\n"
        } else {
            "</AnnotationAssertion>\n"
        };
        let end = at + FORMS[at..].find(close).unwrap() + close.len();
        let text = format!("{header}{}</Ontology>\n", &FORMS[start..end]);
        let p = clean(&text);
        let theirs = functional(&format!("{ofn_header}{source}\n)\n"));
        assert_eq!(triples(&p), triples(&theirs), "{literal}");
    }
}

/// OWL API writes a `nodeID` as Functional syntax does, `_:` and a name
